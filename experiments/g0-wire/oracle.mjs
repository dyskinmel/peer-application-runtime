const bytes=(lo,hi=lo)=>v=>Buffer.isBuffer(v)&&v.length>=lo&&v.length<=hi;
const text=(lo,hi)=>v=>typeof v==='string'&&Buffer.byteLength(v,'utf8')>=lo&&Buffer.byteLength(v,'utf8')<=hi;
