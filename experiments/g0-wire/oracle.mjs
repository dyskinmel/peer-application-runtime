const MAX = 1048576, NODES = 100000, U64 = (1n << 64n)-1n;
class Reject extends Error { constructor(code) { super(code);this.code=code; } }
function no(code) { throw new Reject(code); }
function head(major,n) {
  if(n<0n||n>U64)no('UINT_RANGE');
  if(n<24n)return Buffer.from([(major<<5)|Number(n)]);
  for(const [ai,w] of [[24,1],[25,2],[26,4],[27,8]]) {
    if(n<(1n<<BigInt(8*w))) {
      const b=Buffer.alloc(w+1);b[0]=(major<<5)|ai;
      for(let j=w;j>0;j--){b[j]=Number(n&255n);n>>=8n;}
      return b;
    }
  }
  no('UINT_RANGE');
}
function validUnicode(s) {
  for(let i=0;i<s.length;i++) {
    const c=s.charCodeAt(i);
    if(c>=0xd800&&c<=0xdbff) { const n=s.charCodeAt(++i);if(!(n>=0xdc00&&n<=0xdfff))no('UTF8'); }
    else if(c>=0xdc00&&c<=0xdfff)no('UTF8');
  }
}
export function encode(value) {
  const parts=[];let size=0,nodes=0;const active=new Set();
  const append=b=>{size+=b.length;if(size>MAX)no('LIMIT');parts.push(b);};
  function write(v,depth) {
    if(depth>32)no('DEPTH');if(++nodes>NODES)no('RESOURCE_LIMIT');
    if(v===null){append(Buffer.from([0xf6]));return;}
    if(typeof v==='boolean'){append(Buffer.from([v?0xf5:0xf4]));return;}
    if(typeof v==='bigint'){if(v<0n)no('FORBIDDEN_TYPE');append(head(0,v));return;}
    if(Buffer.isBuffer(v)){append(head(2,BigInt(v.length)));append(v);return;}
    if(typeof v==='string') {
      if(v.length>MAX)no('LIMIT');validUnicode(v);const b=Buffer.from(v,'utf8');append(head(3,BigInt(b.length)));append(b);return;
    }
    if(!Array.isArray(v)&&!(v instanceof Map))no('FORBIDDEN_TYPE');
    if(active.has(v))no('CYCLE');active.add(v);
    if(Array.isArray(v)){if(v.length>NODES)no('RESOURCE_LIMIT');append(head(4,BigInt(v.length)));for(const x of v)write(x,depth+1);}
    else {
      if(v.size>NODES)no('RESOURCE_LIMIT');
      const keys=[...v.keys()];if(keys.some(k=>typeof k!=='bigint'||k<0n||k>U64))no('MAP_KEY');
      keys.sort((a,b)=>a<b?-1:a>b?1:0);append(head(5,BigInt(v.size)));
      for(const k of keys){write(k,depth+1);write(v.get(k),depth+1);}
    }
    active.delete(v);
  }
  write(value,0);return Buffer.concat(parts,size);
}
export function decode(data) {
  if(data.length>MAX)no('LIMIT');let pos=0,nodes=0,result,hasResult=false;
  const stack=[];
  const take=n=>{if(n>data.length-pos)no('TRUNCATED');const b=data.subarray(pos,pos+n);pos+=n;return b;};
  function arg(ai) {
    if(ai<24)return BigInt(ai);if(ai===31)no('INDEFINITE');if(ai>27)no('RESERVED');
    const w=2**(ai-24),b=take(w);let n=0n;for(const v of b)n=(n<<8n)|BigInt(v);
    if(n<[24n,256n,65536n,4294967296n][ai-24])no('NON_MINIMAL');return n;
  }
  // Iterative container stack intentionally differs from the Python recursion.
  function deliver(value) {
    for(;;) {
      if(stack.length===0){result=value;hasResult=true;return;}
      const parent=stack[stack.length-1];
      if(parent.map) {
        if(parent.key===null) {
          if(typeof value!=='bigint')no('MAP_KEY');if(value<=parent.previous)no('MAP_ORDER');
          parent.previous=value;parent.key=value;
        } else {parent.value.set(parent.key,value);parent.key=null;}
      } else parent.value.push(value);
      if(--parent.remaining>0)return;
      value=parent.value;stack.pop();
    }
  }
  while(!hasResult) {
    if(stack.length>32)no('DEPTH');if(++nodes>NODES)no('RESOURCE_LIMIT');
    const byte=take(1)[0],major=byte>>5,ai=byte&31;
    if(major===7){if(ai===20)deliver(false);else if(ai===21)deliver(true);else if(ai===22)deliver(null);else no('FORBIDDEN_TYPE');continue;}
    if(![0,2,3,4,5].includes(major))no('FORBIDDEN_TYPE');
    const n=arg(ai);if(major===0){deliver(n);continue;}
    if(n>BigInt(MAX))no('LIMIT');const count=Number(n);
    if(major===2){deliver(Buffer.from(take(count)));continue;}
    if(major===3){const b=take(count);let text;try{text=new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(b);}catch{no('UTF8');}deliver(text);continue;}
    const remaining=count*(major===5?2:1);
    if(remaining>data.length-pos)no('TRUNCATED');if(nodes+remaining>NODES)no('RESOURCE_LIMIT');
    const value=major===5?new Map():[];
    if(!remaining){deliver(value);continue;}
    stack.push({value,map:major===5,remaining,key:null,previous:-1n});
  }
  if(pos!==data.length)no('TRAILING');return result;
}

